import { moduleId, type ProjectGraph } from './analyze.js'
import type { ArchConfig } from './config.js'
import { boundariesOf, boundaryLookup, type Violation } from './rules.js'

export interface DiagramNode {
  id: string
  name: string
  global: boolean
  boundary?: string
}

export interface DiagramEdge {
  from: string
  to: string
  /** "import" is a Nest module import, "uses" is code that reaches another module without one */
  kind: 'import' | 'uses'
  forwardRef: boolean
  violation: boolean
}

export interface DiagramModel {
  nodes: DiagramNode[]
  edges: DiagramEdge[]
}

export function diagramModel(config: ArchConfig, graph: ProjectGraph, violations: Violation[]): DiagramModel {
  const boundaryOf = config.boundaries ? boundaryLookup(boundariesOf(config, graph), graph) : undefined
  const nodes = graph.modules.map((m) => ({
    id: moduleId(m),
    name: m.name,
    global: m.global,
    boundary: boundaryOf?.(m.file),
  }))
  const ids = new Set(nodes.map((n) => n.id))
  const edges = new Map<string, DiagramEdge>()
  const edge = (from: string, to: string, kind: DiagramEdge['kind']) => {
    const key = `${from}>${to}`
    let e = edges.get(key)
    if (!e) edges.set(key, (e = { from, to, kind, forwardRef: false, violation: false }))
    if (kind === 'import') e.kind = 'import'
    return e
  }
  for (const m of graph.modules) {
    for (const r of m.imports) {
      const to = `${r.file}#${r.name}`
      if (r.file && ids.has(to) && to !== moduleId(m))
        edge(moduleId(m), to, 'import').forwardRef ||= !!r.forwardRef
    }
  }
  for (const imp of graph.imports) {
    if (!imp.to) continue
    const a = graph.owner(imp.from)
    const b = graph.owner(imp.to)
    if (a && b && a !== b) edge(moduleId(a), moduleId(b), 'uses')
  }
  for (const v of violations) {
    for (const [a, b] of v.edges ?? [])
      if (ids.has(a) && ids.has(b) && a !== b) edge(a, b, 'uses').violation = true
  }
  const sorted = [...edges.values()].sort((a, b) => a.from.localeCompare(b.from) || a.to.localeCompare(b.to))
  return { nodes, edges: sorted }
}

export function toMermaid(model: DiagramModel): string {
  const short = new Map(model.nodes.map((n, i) => [n.id, `m${i}`]))
  const node = (n: DiagramNode) => `${short.get(n.id)}["${n.name}${n.global ? ' (global)' : ''}"]`
  const lines = ['flowchart TD']
  const groups = new Map<string, DiagramNode[]>()
  for (const n of model.nodes) {
    if (n.boundary) groups.set(n.boundary, [...(groups.get(n.boundary) ?? []), n])
    else lines.push(`  ${node(n)}`)
  }
  let g = 0
  for (const [name, members] of [...groups].sort(([a], [b]) => a.localeCompare(b))) {
    lines.push(`  subgraph b${g++}["${name}"]`, ...members.map((n) => `    ${node(n)}`), '  end')
  }
  const red: number[] = []
  model.edges.forEach((e, i) => {
    const arrow = e.kind === 'import' ? (e.forwardRef ? '-->|forwardRef|' : '-->') : '-.->'
    lines.push(`  ${short.get(e.from)} ${arrow} ${short.get(e.to)}`)
    if (e.violation) red.push(i)
  })
  if (red.length) lines.push(`  linkStyle ${red.join(',')} stroke:#cf222e,stroke-width:2px`)
  const globals = model.nodes.filter((n) => n.global).map((n) => short.get(n.id))
  if (globals.length)
    lines.push('  classDef global stroke-dasharray:5 4', `  class ${globals.join(',')} global`)
  return lines.join('\n')
}

const START = '<!-- nest-arch-guard:start -->'
const END = '<!-- nest-arch-guard:end -->'

export function updateMarkdown(existing: string | undefined, mermaid: string): string {
  const block = [
    START,
    '<!-- Generated by nest-arch-guard. Edit arch.config instead and run `nest-arch-guard diagram`. -->',
    '',
    '```mermaid',
    mermaid,
    '```',
    '',
    'Solid arrows are Nest module imports. Dashed arrows are code that uses another module without importing it (usually a global module). Red marks a rule violation.',
    END,
  ].join('\n')
  if (!existing) return `# Architecture\n\n${block}\n`
  const s = existing.indexOf(START)
  const e = existing.indexOf(END)
  if (s === -1 || e === -1) return `${existing.trimEnd()}\n\n${block}\n`
  return existing.slice(0, s) + block + existing.slice(e + END.length)
}

const PALETTE = ['#ddf4ff', '#dafbe1', '#fff8c5', '#ffebe9', '#fbefff', '#ffeff7', '#f6f8fa', '#d8f3f1']

export function toSvg(model: DiagramModel): string {
  const H = 34
  const GAP_X = 28
  const GAP_Y = 76
  const M = 24
  const width = (n: DiagramNode) => Math.round(Math.max(110, (n.name.length + (n.global ? 9 : 0)) * 7.6 + 32))
  const byId = new Map(model.nodes.map((n) => [n.id, n]))
  // Layers come from Nest imports only. "uses" edges are drawn on top without moving nodes.
  const imports = model.edges.filter((e) => e.kind === 'import')
  const out = new Map<string, string[]>(model.nodes.map((n) => [n.id, []]))
  for (const e of imports) out.get(e.from)?.push(e.to)
  const indeg = new Map(model.nodes.map((n) => [n.id, 0]))
  for (const e of imports) indeg.set(e.to, (indeg.get(e.to) ?? 0) + 1)
  const order = [...model.nodes].sort(
    (a, b) => indeg.get(a.id)! - indeg.get(b.id)! || a.name.localeCompare(b.name),
  )
  const state = new Map<string, 1 | 2>()
  const back = new Set<string>()
  const dfs = (v: string) => {
    state.set(v, 1)
    for (const w of out.get(v) ?? []) {
      if (state.get(w) === 1) back.add(`${v}>${w}`)
      else if (!state.has(w)) dfs(w)
    }
    state.set(v, 2)
  }
  for (const n of order) if (!state.has(n.id)) dfs(n.id)
  const forward = imports.filter((e) => !back.has(`${e.from}>${e.to}`))
  const layer = new Map(model.nodes.map((n) => [n.id, 0]))
  // ponytail: Bellman-Ford style longest path, O(V·E); fine for the module counts Nest apps have.
  for (let i = 0; i < model.nodes.length; i++) {
    for (const e of forward) layer.set(e.to, Math.max(layer.get(e.to)!, layer.get(e.from)! + 1))
  }
  const layers: string[][] = []
  for (const n of order) (layers[layer.get(n.id)!] ??= []).push(n.id)
  for (const l of layers) l.sort((a, b) => byId.get(a)!.name.localeCompare(byId.get(b)!.name))

  const pos = () => new Map(layers.flatMap((l) => l.map((id, i) => [id, i] as const)))
  for (let iter = 0; iter < 4; iter++) {
    for (let li = 1; li < layers.length; li++) {
      const p = pos()
      const bary = (id: string) => {
        const preds = forward
          .filter((e) => e.to === id && layer.get(e.from) === li - 1)
          .map((e) => p.get(e.from)!)
        return preds.length ? preds.reduce((a, b) => a + b, 0) / preds.length : p.get(id)!
      }
      layers[li]!.sort((a, b) => bary(a) - bary(b))
    }
  }

  const layerWidth = (l: string[]) =>
    l.reduce((s, id) => s + width(byId.get(id)!), 0) + GAP_X * (l.length - 1)
  const inner = Math.max(...layers.map(layerWidth), 200)
  const xy = new Map<string, { x: number; y: number; w: number }>()
  layers.forEach((l, li) => {
    let x = M + (inner - layerWidth(l)) / 2
    for (const id of l) {
      const w = width(byId.get(id)!)
      xy.set(id, { x, y: M + li * (H + GAP_Y), w })
      x += w + GAP_X
    }
  })

  const boundaries = [...new Set(model.nodes.map((n) => n.boundary).filter((b): b is string => !!b))].sort()
  const fill = (b?: string) => (b ? PALETTE[boundaries.indexOf(b) % PALETTE.length]! : '#ffffff')
  const esc = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;')

  const rowWidth = Math.max(inner, 460)
  const legend: { w: number; svg: (x: number, y: number) => string; newRow?: boolean }[] = [
    ['#6e7781', '', 'imports'],
    ['#6e7781', ' stroke-dasharray="5 4"', 'uses without importing'],
    ['#cf222e', '', 'rule violation'],
  ].map(([color, dash, label]) => ({
    w: 36 + label!.length * 6.8 + 24,
    svg: (x, y) =>
      `<line x1="${x}" y1="${y}" x2="${x + 28}" y2="${y}" stroke="${color}" stroke-width="2"${dash}/>` +
      `<text x="${x + 36}" y="${y + 4.5}" fill="#57606a" font-size="12">${label}</text>`,
  }))
  boundaries.forEach((b, i) =>
    legend.push({
      newRow: i === 0,
      w: 22 + b.length * 6.8 + 20,
      svg: (x, y) =>
        `<rect x="${x}" y="${y - 8}" width="16" height="16" rx="3" fill="${fill(b)}" stroke="#57606a"/>` +
        `<text x="${x + 22}" y="${y + 4.5}" fill="#57606a" font-size="12">${esc(b)}</text>`,
    }),
  )
  let lx = M
  let ly = M + layers.length * (H + GAP_Y) - GAP_Y + 36
  const legendSvg: string[] = []
  for (const item of legend) {
    if (item.newRow || lx + item.w > M + rowWidth) {
      lx = M
      ly += 26
    }
    legendSvg.push(item.svg(lx, ly))
    lx += item.w
  }
  const totalW = rowWidth + M * 2 + 60
  const totalH = ly + 12 + M

  const parts: string[] = [
    `<svg xmlns="http://www.w3.org/2000/svg" width="${totalW}" height="${totalH}" viewBox="0 0 ${totalW} ${totalH}" font-family="Helvetica, Arial, sans-serif" font-size="13">`,
    '<defs>',
    '<marker id="a" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="#6e7781"/></marker>',
    '<marker id="r" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="7" markerHeight="7" orient="auto-start-reverse"><path d="M0 0L10 5L0 10z" fill="#cf222e"/></marker>',
    '</defs>',
    '<rect width="100%" height="100%" fill="#ffffff"/>',
  ]
  const shift = (rowWidth - inner) / 2
  for (const p of xy.values()) p.x += shift
  const gapX = (li: number, want: number) => {
    const boxes = layers[li]!.map((id) => xy.get(id)!).sort((p, q) => p.x - q.x)
    const gaps: [number, number][] = []
    let left = -Infinity
    for (const box of boxes) {
      gaps.push([left, box.x - 8])
      left = box.x + box.w + 8
    }
    gaps.push([left, Infinity])
    let best = want
    let dist = Infinity
    for (const [lo, hi] of gaps) {
      if (hi < lo) continue
      const x = Math.min(Math.max(want, lo === -Infinity ? hi - 24 : lo), hi === Infinity ? lo + 24 : hi)
      if (Math.abs(x - want) < dist) [best, dist] = [x, Math.abs(x - want)]
    }
    return best
  }
  for (const e of [...model.edges].sort((a, b) => Number(a.violation) - Number(b.violation))) {
    const a = xy.get(e.from)
    const b = xy.get(e.to)
    if (!a || !b) continue
    const [la, lb] = [layer.get(e.from)!, layer.get(e.to)!]
    const [ax, bx] = [a.x + a.w / 2, b.x + b.w / 2]
    let d: string
    if (lb !== la) {
      const down = lb > la
      const [y1, y2] = down ? [a.y + H, b.y] : [a.y, b.y + H]
      // Edges that skip layers pass through gaps between the nodes in the layers they cross.
      const points: [number, number][] = [[ax, y1]]
      const step = down ? 1 : -1
      for (let li = la + step; li !== lb; li += step) {
        const t = (li - la) / (lb - la)
        points.push([gapX(li, ax + (bx - ax) * t), M + li * (H + GAP_Y) + H / 2])
      }
      points.push([bx, y2])
      d = `M${points[0]![0]} ${points[0]![1]}`
      for (let i = 1; i < points.length; i++) {
        const [px, py] = points[i - 1]!
        const [qx, qy] = points[i]!
        const dy = (qy - py) / 2
        d += `C${px} ${py + dy} ${qx} ${qy - dy} ${qx} ${qy}`
      }
    } else {
      const dip = 30 + Math.abs(ax - bx) / 8
      d = `M${ax} ${a.y + H}C${ax} ${a.y + H + dip} ${bx} ${b.y + H + dip} ${bx} ${b.y + H}`
    }
    const stroke = e.violation ? '#cf222e' : '#6e7781'
    const dash = e.kind === 'uses' ? ' stroke-dasharray="5 4"' : ''
    parts.push(
      `<path d="${d}" fill="none" stroke="${stroke}" stroke-width="${e.violation ? 2 : 1.3}"${dash} marker-end="url(#${e.violation ? 'r' : 'a'})"/>`,
    )
  }
  for (const n of model.nodes) {
    const p = xy.get(n.id)!
    const dash = n.global ? ' stroke-dasharray="4 3"' : ''
    parts.push(
      `<rect x="${p.x}" y="${p.y}" width="${p.w}" height="${H}" rx="6" fill="${fill(n.boundary)}" stroke="#57606a"${dash}/>`,
      `<text x="${p.x + p.w / 2}" y="${p.y + H / 2 + 4.5}" text-anchor="middle" fill="#1f2328">${esc(n.name)}${n.global ? '<tspan fill="#6e7781"> (global)</tspan>' : ''}</text>`,
    )
  }
  parts.push(...legendSvg, '</svg>')
  return parts.join('\n')
}
